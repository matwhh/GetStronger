-- =============================================================================
-- РОБОТА ЗА РОЗКЛАДОМ УСЕРЕДИНІ БАЗИ (pg_cron)
-- =============================================================================
-- Застосовано міграцією elo_cron_eval_week. Цей файл — документація стану,
-- а не те, що треба запускати руками.
--
-- ЩО БУЛО НЕ ТАК. elo_evaluate_week() працює від auth.uid(), тобто підбиває
-- тиждень лише тому, хто зараз у застосунку. Поки людина не зайшла, штрафи
-- за пропущені тренування й бонус за чистий тиждень не нараховані. Тобто
-- економіка залежала від того, чи хтось відкрив сайт.
--
-- ЩО ТЕПЕР. public.elo_cron_eval_week() робить те саме для всіх схвалених
-- користувачів і не потребує сесії. pg_cron кличе її щодня о 00:10 UTC.
--
-- ЧОМУ ЩОДНЯ, А НЕ ПО ПОНЕДІЛКАХ — див. коментар у самій функції: неділю
-- можна здати ще два дні, тож тиждень стає придатним лише коли
-- current_date > неділя + submitWindowDays. Щоденний прогін заразом
-- лікує пропущений день і не робить нічого, коли робити нема чого.
--
-- ЯК ПОДИВИТИСЬ, ЧИ ПРАЦЮЄ:
--   select * from cron.job;                       -- розклад
--   select * from cron.job_run_details            -- історія запусків
--     order by start_time desc limit 20;          -- return_message = наш jsonb
--
-- ЯК ЗУПИНИТИ:
--   select cron.unschedule('forge-elo-week');
--
-- ЩО СЮДИ ЩЕ НЕ ДОДАНО. Закриття сезону (elo_close_season) теж прив'язане
-- до auth.uid() і роздає нагороди по одному користувачу. Щоб винести його
-- в cron, функцію треба спершу розділити на _for(uid, season) і обгортку —
-- це окрема правка з ризиком зачепити season_history й awards. Сезон
-- закривається 2026-12-03, часу вдосталь.
-- =============================================================================

create extension if not exists pg_cron with schema pg_catalog;
grant usage on schema cron to postgres;
grant all privileges on all tables in schema cron to postgres;

select cron.schedule('forge-elo-week', '10 0 * * *', $$select public.elo_cron_eval_week()$$);

-- DB-008. Закриття сезону. 03:40 UTC — після нічної оцінки тижня (00:10) і
-- після чистки покинутих реєстрацій (03:20), щоб підсумок бачив уже
-- дорахований останній тиждень. Функція сама нічого не робить, поки сезон
-- не завершився й не минуло вікно дописування.
select cron.schedule('forge-close-season', '40 3 * * *', $$select public.elo_cron_log_close_seasons()$$);
