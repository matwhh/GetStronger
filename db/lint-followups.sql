-- -----------------------------------------------------------------------------
-- 1. RLS без політик — це deny-all, і саме так задумано
-- -----------------------------------------------------------------------------
--
-- Обидві таблиці службові: у них пише ЛИШЕ сервер із SECURITY DEFINER-функцій,
-- які виконуються від власника й політик не питають. Увімкнений RLS без
-- жодної політики означає «нікому з anon і authenticated», і це найсуворіший
-- можливий стан — не недогляд.

comment on table public.cron_log is
  'Журнал щоденного підбиття (elo_cron_eval_week). RLS увімкнено БЕЗ політик '
  'навмисно: це deny-all для anon і authenticated. Пише сюди лише '
  'elo_cron_log_eval_week (SECURITY DEFINER, від власника), читає власник '
  'вручну. Лінтер Supabase показує це як rls_enabled_no_policy — додавати '
  'політику НЕ треба, вона відкриє таблицю.';

comment on table public.elo_week_plan is
  'Знімок тижневого плану для оцінки тижня. RLS увімкнено БЕЗ політик '
  'навмисно: це deny-all для anon і authenticated. Пишуть і читають лише '
  'SECURITY DEFINER-функції рушія ELO. Лінтер Supabase показує це як '
  'rls_enabled_no_policy — політика тут відкрила б чужі плани.';

-- -----------------------------------------------------------------------------
-- 2. Зовнішній ключ без покривного індексу — справжня дрібниця, закриваємо
-- -----------------------------------------------------------------------------
--
-- account_status.decided_by → auth.users(id). Без індексу видалення
-- користувача з auth.users змушує Postgres прочитати account_status цілком,
-- щоб переконатись, що на нього ніхто не посилається. На теперішніх обсягах
-- це мілісекунди, але delete_account — операція, яку людина робить із
-- почуттям «зараз усе зникне», і чекати там не варто взагалі.
--
-- if not exists: міграцію можна виконати повторно, не ловлячи 42P07.

create index if not exists account_status_decided_by_idx
  on public.account_status (decided_by);

-- -----------------------------------------------------------------------------
-- 3. Що лінтер показує, а чіпати НЕ треба
-- -----------------------------------------------------------------------------
--
-- unused_index: cron_log_job_time і account_status_status_requested_idx
-- «жодного разу не використані». Це правда й нічого не означає: у таблицях
-- одиниці рядків, і планувальник чесно бере seq scan — індекс дешевший за
-- перегляд трьох рядків не буває. Обидва обслуговують запити, які вже
-- написані (db/README.md: `select run_at, result from cron_log where job = …
-- order by run_at desc`; admin_requests(p_status, …)), і зникнуть саме тоді,
-- коли почнуть бути потрібні. Видалити їх — означає повернути їх через
-- півроку, коли той самий запит почне гальмувати на тисячі рядків.
--
-- auth_rls_initplan на elo_config_read: політика вже має вигляд
-- `(select is_approved(auth.uid()))`, тобто це скалярний підзапит —
-- InitPlan, обчислений ОДИН раз. Лінтер шукає літерально `auth.<fn>()`, не
-- загорнутий у select, і не бачить, що обгортка стоїть рівнем вище. До того
-- ж у elo_config рівно один рядок (CHECK id = 1), тож «переобчислення на
-- кожен рядок» тут — це переобчислення один раз. Переписувати заради
-- зеленого рядка в лінтері немає чого.
