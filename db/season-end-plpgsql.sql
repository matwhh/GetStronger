-- =============================================================================
-- season_end: ІЗ SQL У PLPGSQL, ЩОБ ЗНІМОК СХЕМИ ЗНОВУ РОЗГОРТАВСЯ
-- Міграція: season_end_plpgsql
-- =============================================================================
--
-- ЩО БУЛО ЗЛАМАНО. `db/dump-live-schema.sql` виводить функції в АЛФАВІТНОМУ
-- порядку — за іменем, не за залежностями. Тіло sql-функції Postgres
-- розбирає в момент створення, тобто всі виклики в ньому мусять уже
-- існувати. season_end написана мовою sql і кличе season_nominal_end, а та
-- за алфавітом стоїть НИЖЧЕ. Отже свіжий знімок не розгортався зовсім:
--
--   ERROR:  function public.season_nominal_end(text) does not exist
--
-- Чому цього не було видно: знімок у репозиторії відстав від бази на три
-- міграції й містив стару season_end, якій season_nominal_end не потрібна.
-- Тобто зламане ховалось за застарілим. Виявилось рівно тоді, коли знімок
-- перезняли.
--
-- ЧОМУ ЦЕ ДОРОГО. Знімок — не документ для читання: на ньому стоять усі
-- серверні перевірки (tools/verify-sql-suites.mjs, verify-elo-week.mjs
-- розгортають його в тимчасовий Postgres) і з нього відтворюється схема при
-- відновленні. Знімок, який не розгортається, знімає 92 серверні тести
-- одним рухом — і мовчки.
--
-- ЛІКУВАННЯ — ТЕ САМЕ, ЩО ВЖЕ ЗАСТОСУВАЛИ. plpgsql-тіло компілюється при
-- ПЕРШОМУ виклику, а не при створенні, тож порядок оголошень йому байдужий.
-- Рівно так уже вчинили з elo_week_room (див. коментар у db/elo-pace.sql,
-- розділ 3), і з тієї самої причини.
--
-- ЛОГІКА НЕ ЗМІНЕНА НІ НА ДЕНЬ. Значення для дванадцяти сезонів 2025–2027,
-- для сміття на вході й для null звірені до й після міграції — збігаються
-- усі.
-- =============================================================================

CREATE OR REPLACE FUNCTION public.season_end(p_season text)
 RETURNS date
 LANGUAGE plpgsql
 IMMUTABLE
 SET search_path TO 'public'
AS $function$
declare nom date;
begin
  nom := public.season_nominal_end(p_season);
  if nom is null then return null; end if;
  -- До вересня 2026 сезон закінчувався номінальною датою; далі — найближчою
  -- неділею від неї, щоб тижні сезону були цілими (season_week_bounds).
  if nom < date '2026-09-01' then return nom; end if;
  return nom + ((7 - extract(isodow from nom)::int) % 7);
end $function$;
