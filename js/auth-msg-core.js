/**
 * Що САМЕ не так із введеним — чисті функції, без DOM.
 *
 * ЧОМУ ЦЕ ОКРЕМИЙ МОДУЛЬ. Форма входу казала одне на всі випадки:
 * «Заповніть пошту й пароль (від 8 символів)». Людина з порожнім полем,
 * людина з пробілом у кінці адреси, людина, яка набрала пошту кирилицею,
 * і людина, яка просто не дописала домен, бачили той самий рядок — і
 * жодна з них не знала, куди дивитись. Помилка, яка не називає поле й
 * причину, нічим не краща за мовчання.
 *
 * Тут — тільки текст і назва поля. Показ (підсвітити поле, поставити
 * фокус) лишається в js/welcome.js, бо це вже DOM.
 *
 * ПРО МЕЖУ З PasswordCore. Той модуль про НАДІЙНІСТЬ нового пароля
 * (склад, словники, візерунки). Тут — про те, чи взагалі можна
 * надсилати форму, і про переклад серверної відмови в поле. Плутати їх
 * не можна: на вході чужий слабкий пароль — не наша справа, туди його
 * треба пропустити як є.
 */
(function () {
  'use strict';

  /* Та сама перевірка, що й на решті екранів: щось@щось.щось без пробілів. */
  const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

  const CYR = /[Ѐ-ӿ]/;

  /**
   * Чому ця адреса не годиться.
   * @param {string} raw що набрала людина
   * @returns {string} порожньо, якщо все гаразд
   */
  function emailProblem(raw) {
    const s = String(raw == null ? '' : raw);
    const t = s.trim();

    if (!t) return 'Введіть пошту — без неї ми не знаємо, чий це акаунт.';

    /* Пробіл усередині найчастіше приїздить із автозаміни на телефоні
       або з копіювання — людина його просто не бачить. */
    if (/\s/.test(t)) return 'У пошті є пробіл. Приберіть його — в адресі пробілів не буває.';

    /* Кирилиця — це майже завжди незакрита розкладка, а не справжня
       адреса з кириличним доменом. Сказати про розкладку корисніше, ніж
       про «невірний формат». */
    if (CYR.test(t)) return 'Пошта набрана кирилицею. Перемкніть розкладку на англійську й наберіть ще раз.';

    const at = t.indexOf('@');
    if (at === -1) return 'У пошті немає знака @. Адреса має вигляд імʼя@пошта.com.';
    if (t.indexOf('@', at + 1) !== -1) return 'У пошті два знаки @. Лишіть один: імʼя@пошта.com.';
    if (at === 0) return 'Перед @ нічого немає. Спершу йде імʼя скриньки: імʼя@пошта.com.';

    const domain = t.slice(at + 1);
    if (!domain) return 'Після @ немає домену. Допишіть, наприклад, gmail.com.';
    if (domain.indexOf('.') === -1) return 'У домені після @ немає крапки. Має бути на кшталт gmail.com.';
    if (/^\.|\.$/.test(domain) || domain.indexOf('..') !== -1) {
      return 'У домені після @ крапка стоїть не на місці. Має бути на кшталт gmail.com.';
    }
    if (domain.split('.').pop().length < 2) {
      return 'Домен обірваний після останньої крапки. Має бути на кшталт gmail.com.';
    }

    if (!EMAIL_RE.test(t)) return 'Пошта написана з помилкою. Має бути вигляду імʼя@пошта.com.';
    return '';
  }

  /* Має збігатися з PasswordCore.MIN_LEN і з Supabase Auth. */
  const MIN_LEN = 8;

  /**
   * Чому цей пароль не можна навіть НАДІСЛАТИ на вхід.
   *
   * Це не оцінка надійності: чужий пароль може бути яким завгодно, і
   * судити його на вході — не наша справа. Ловимо лише те, після чого
   * запит гарантовано не має сенсу.
   *
   * @param {string} raw
   * @returns {string} порожньо, якщо можна надсилати
   */
  function loginPassProblem(raw) {
    const s = String(raw == null ? '' : raw);
    if (!s) return 'Введіть пароль.';
    if (s.length < MIN_LEN) {
      return 'Пароль закороткий: у ньому ' + s.length + ' ' + plural(s.length) +
             ', а найкоротший можливий — ' + MIN_LEN + '. Схоже, він набраний не повністю.';
    }
    if (CYR.test(s)) {
      return 'Пароль набраний кирилицею, а паролі на сайті лише латиницею. ' +
             'Перемкніть розкладку на англійську.';
    }
    return '';
  }

  function plural(n) {
    const t = n % 10, h = n % 100;
    if (t === 1 && h !== 11) return 'символ';
    if (t >= 2 && t <= 4 && (h < 12 || h > 14)) return 'символи';
    return 'символів';
  }

  /*
   * Серверна відмова → поле + текст.
   *
   * Store вже перекладає коди Supabase людською мовою (AUTH_MSG), але не
   * знає нічого про форму. Тут вирішується друге питання: КУДИ дивитись
   * і що робити далі.
   *
   * Окремо про invalid_credentials. Сервер навмисно не каже, що саме не
   * підійшло — пошта чи пароль: інакше формою входу можна перевіряти,
   * чи зареєстрований конкретний чоловік. Ми цю межу не переступаємо,
   * але замість глухого «не вдалося увійти» показуємо дві найчастіші
   * причини й вихід — відновлення пароля.
   */
  function signInProblem(err) {
    const code = String((err && err.code) || '');
    const text = String((err && err.message) || '');

    if (err && err.offline) {
      return { field: '', text: text || 'Немає звʼязку з сервером.', action: '' };
    }
    if (code === 'email_not_confirmed') {
      return { field: '', action: 'confirm',
               text: 'Пошта ще не підтверджена. Відкрийте лист «Confirm your email» ' +
                     'і натисніть у ньому посилання — після цього вхід запрацює.' };
    }
    if (code === 'invalid_credentials') {
      return { field: 'au-pass', action: 'forgot',
               text: 'Пошта або пароль не підходять. Найчастіше це Caps Lock або ' +
                     'незакрита розкладка. Якщо пароль забули — відновіть його нижче.' };
    }
    if (code === 'over_request_rate_limit' || (err && err.status === 429)) {
      return { field: '', action: '',
               text: text || 'Забагато спроб поспіль. Зачекайте хвилину й повторіть.' };
    }
    if (code === 'user_banned') {
      return { field: '', action: '', text: 'Цей акаунт заблоковано.' };
    }
    return { field: '', action: '', text: text || 'Не вдалося увійти.' };
  }

  window.AuthMsg = {
    EMAIL_RE: EMAIL_RE,
    MIN_LEN: MIN_LEN,
    emailProblem: emailProblem,
    loginPassProblem: loginPassProblem,
    signInProblem: signInProblem
  };
}());
