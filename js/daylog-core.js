/**
 * ДВА ЖУРНАЛИ ДНЯ: тренування і вага. Одні правила на весь сайт.
 *
 * НАВІЩО ЦЕЙ ФАЙЛ. Питання «чи був цього дня тренувальний день» уміли
 * відповідати ДВА файли по-своєму: journal.js (trained + sessionCounts)
 * і today.js (trainedOn). Код майже збігався, але саме «майже» тут і
 * небезпечне: журнал уміє явний нуль як «знято руками», а плитка на
 * «Сьогодні» — теж уміла, бо її писали, дивлячись у журнал. Наступна
 * правка в одному з них розійшлася б тихо: календар показував би
 * тренування, а квадратик на головній — ні, і людина побачила б два
 * різні факти про один свій день.
 *
 * Тепер сюди ж переїхали правила запису ваги (межі, крок, розбір
 * введеного рядка), бо після появи окремих сторінок «Дні тренувань» і
 * «Зважування» місць, що пишуть у ті самі журнали, стало по три.
 *
 * БЕЗ DOM. Жодного document, жодного Store: на вхід — журнали з профілю,
 * на вихід — НОВІ обʼєкти. Мутувати вхідний журнал не можна: той самий
 * обʼєкт лежить у state сторінки, і зміна «на місці» показала б новий
 * стан ще до того, як збереження підтвердилось (або провалилось).
 *
 * ЗАЛЕЖНІСТЬ ОДНА — window.DateCore (ключі днів і зсуви). Дати місцеві,
 * різниці — в UTC; чому саме так, написано в js/date-core.js.
 */
(function () {
  'use strict';

  /* Ті самі фізіологічні межі, що в ядрі харчування. Нижче 30 і вище 300
     кг — це майже завжди описка на порядок (8.24 замість 82.4), а не
     людина: формули харчування на таких числах усе одно нічого
     осмисленого не дадуть. */
  var W_MIN = 30, W_MAX = 300;

  var KEY = /^\d{4}-\d{2}-\d{2}$/;

  function isKey(k) { return KEY.test(String(k == null ? '' : k)); }

  function obj(o) {
    return (o && typeof o === 'object' && !Array.isArray(o)) ? o : {};
  }

  /* ================================================================== */
  /* ТРЕНУВАННЯ                                                          */
  /* ================================================================== */

  /**
   * Чи є в записі сесії робота.
   *
   * done — це закриті ВПРАВИ, і відколи виконання відмічається по
   * підходах, день із чотирма закритими підходами, але жодною добитою
   * вправою, мав done === 0: людина тренувалась, а календар лишався
   * порожнім. Тому дивимось і на підходи.
   */
  function sessionCounts(s) {
    if (!s || typeof s !== 'object') return false;
    return Number(s.done) > 0 || Number(s.doneSets) > 0;
  }

  /** Чи є під днем сесія з екрана «Тренування». */
  function hasSession(sessionLog, key) {
    return sessionCounts(obj(sessionLog)[key]);
  }

  /**
   * День або тренувальний, або ні — саме це вмикає й вимикає клік.
   *
   * ЯВНИЙ 0 ПЕРЕКРИВАЄ СЕСІЮ. Раніше нуль не відрізнявся від
   * відсутнього запису, а перемикач умів лише delete. Тож день,
   * підсвічений сесією з «Тренування», не можна було зняти взагалі:
   * delete нічого не міняв, sessionLog лишався, клітинка світилась далі
   * — і продовжувала годувати статистику дотримання плану та рейтинг.
   * Підказка «клікніть, щоб зняти» була неправдою.
   */
  function trained(workLog, sessionLog, key) {
    var v = Number(obj(workLog)[key]);
    if (Number.isFinite(v)) return v > 0;
    /* Сесія з «Тренування» — теж тренування: підходи й таймер — два
       способи сказати одне й те саме, і клітинка має світитись від обох. */
    return hasSession(sessionLog, key);
  }

  /**
   * Перемкнути ручну позначку дня. Повертає НОВИЙ workLog.
   *
   * Три стани, а не два, і третій неочевидний:
   *   немає ключа      — «нічого не казали», сесія (якщо є) вирішує сама;
   *   1                — «тренувався», навіть якщо сесії немає;
   *   0                — «НЕ тренувався», навіть якщо сесія є.
   * Нуль пишеться лише тоді, коли під днем справді лежить сесія: інакше
   * журнал заростав би нулями, які нічого не перекривають.
   */
  function toggleTrained(workLog, sessionLog, key) {
    var out = Object.assign({}, obj(workLog));
    if (!isKey(key)) return out;
    if (trained(workLog, sessionLog, key)) {
      if (hasSession(sessionLog, key)) out[key] = 0; else delete out[key];
    } else {
      out[key] = 1;
    }
    return out;
  }

  /**
   * РІВЕНЬ ДНЯ 0–4 — скільки, а не лише «чи був».
   *
   * Рівень означає ЯКУ ЧАСТКУ запланованих підходів закрито, тобто рівно
   * те, за що нараховує ELO (js/elo-core.js рахує доданок workout як
   * doneSets/totalSets). Перемикач лишається бінарним: клік вмикає й
   * вимикає ДЕНЬ, рівень усередині нього — похідне від записаних
   * підходів, і клацанням не задається.
   *
   *   0  тренування немає
   *   1  відмічено вручну — підходів не записано, частки ми НЕ ЗНАЄМО
   *   2  закрито менше половини підходів
   *   3  закрито більшу частину
   *   4  закрито все
   *
   * Рівень 1 стоїть окремо навмисно: поставити його поруч із «менше
   * половини» означало б сказати про день те, чого в даних немає.
   */
  function dayLevel(workLog, sessionLog, key) {
    if (!trained(workLog, sessionLog, key)) return 0;
    var s = obj(sessionLog)[key];
    var total = Number(s && s.totalSets);
    var done = Number(s && s.doneSets);
    if (!(total > 0) || !(done > 0)) return 1;      /* відмічено руками */
    var share = done / total;
    if (share >= 0.999) return 4;
    if (share >= 0.5) return 3;
    return 2;
  }

  /* Підпис рівня — той самий текст у підказці й легенді на «Днях
     тренувань» і в календарі історії «Прогресу». Три написання одного й
     того самого пояснення — три різні пояснення через півроку. */
  var LEVEL_TEXT = [
    'без тренування',
    'відмічено вручну — підходи не записані',
    'закрито менше половини підходів',
    'закрито більшу частину підходів',
    'закрито всі підходи'
  ];

  /** Позначити день тренувальним беззастережно (кнопка «Позначити»). */
  function markTrained(workLog, key) {
    var out = Object.assign({}, obj(workLog));
    if (isKey(key)) out[key] = 1;
    return out;
  }

  /* ================================================================== */
  /* ВАГА                                                                */
  /* ================================================================== */

  /**
   * Розібрати те, що людина набрала в полі.
   *
   * Кома — не помилка: на українській розкладці телефона це те, що
   * стоїть на цифровій клавіатурі, і вимагати крапку означало б
   * відхиляти половину введень. Пробіли теж: вони приїжджають із
   * копіювання з ваг чи з нотаток.
   *
   * Крок — 0,1 кг, пів кроку побутових ваг. Точніші цифри — ілюзія
   * точності: різниця в 30 грамів між двома ранками — це вода й час до
   * туалету, а не тіло.
   *
   * Повертає число або null. null означає «не пишемо нічого» — сюди ж
   * потрапляє і порожнє поле, і текст, і число поза межами.
   */
  function parseKg(raw) {
    var s = String(raw == null ? '' : raw).trim().replace(',', '.');
    if (!s) return null;
    var v = Number(s);
    if (!Number.isFinite(v) || v < W_MIN || v > W_MAX) return null;
    return Math.round(v * 10) / 10;
  }

  /** Чи є за цей день запис ваги. */
  function weighed(bodyLog, key) {
    var v = Number(obj(bodyLog)[key]);
    return Number.isFinite(v) && v > 0;
  }

  /** Вага за день або null. */
  function weightAt(bodyLog, key) {
    var v = Number(obj(bodyLog)[key]);
    return (Number.isFinite(v) && v >= W_MIN && v <= W_MAX) ? v : null;
  }

  /**
   * Відсортовані записи ваги: [{key, kg}] від старих до нових.
   *
   * Сміття відсіюється ТУТ, а не в кожного, хто читає журнал: у профіль
   * могло приїхати що завгодно з імпорту або зі старої версії схеми, і
   * графік, побудований по рядку «82,4kg», малює порожнечу мовчки.
   */
  function weightEntries(bodyLog) {
    var log = obj(bodyLog);
    return Object.keys(log)
      .filter(function (k) { return isKey(k) && weightAt(log, k) !== null; })
      .sort()
      .map(function (k) { return { key: k, kg: Number(log[k]) }; });
  }

  /** Записати вагу за день. Повертає НОВИЙ bodyLog. */
  function setWeight(bodyLog, key, kg) {
    var out = Object.assign({}, obj(bodyLog));
    var v = parseKg(kg);
    if (isKey(key) && v !== null) out[key] = v;
    return out;
  }

  /** Прибрати запис ваги за день. Повертає НОВИЙ bodyLog. */
  function removeWeight(bodyLog, key) {
    var out = Object.assign({}, obj(bodyLog));
    delete out[key];
    return out;
  }

  /* ================================================================== */
  /* СПІЛЬНЕ                                                             */
  /* ================================================================== */

  /**
   * День, у який піде наступний запис.
   *
   * Порожній, зіпсований або майбутній вибір відкочується на сьогодні.
   * Майбутнє тут — не прискіпливість: календар малює наступні дні
   * сірими, але ключ у стані переживає північ, і вчорашній вибір
   * «завтра» зранку став би записом ваги за день, який ще не настав.
   */
  function pickDay(sel, today) {
    var t = isKey(today) ? String(today) : window.DateCore.todayKey();
    if (!isKey(sel) || String(sel) > t) return t;
    return String(sel);
  }

  /**
   * Скільки днів тижня має факт. Тиждень — від понеділка, як і скрізь.
   *
   * has — предикат від ключа дня. Рахуємо рівно 7 днів від понеділка, а
   * не «останні 7»: підпис «цього тижня» на «Сьогодні» й на окремій
   * сторінці мусить давати те саме число, інакше одна з двох плиток
   * бреше.
   */
  function weekTally(has, mondayKey) {
    var start = isKey(mondayKey)
      ? String(mondayKey)
      : window.DateCore.keyOf(window.DateCore.mondayOf(new Date()));
    var n = 0;
    for (var i = 0; i < 7; i++) {
      if (has(window.DateCore.shiftKey(start, i))) n++;
    }
    return n;
  }

  window.DayLogCore = {
    W_MIN: W_MIN,
    W_MAX: W_MAX,
    sessionCounts: sessionCounts,
    hasSession: hasSession,
    trained: trained,
    dayLevel: dayLevel,
    LEVEL_TEXT: LEVEL_TEXT,
    toggleTrained: toggleTrained,
    markTrained: markTrained,
    parseKg: parseKg,
    weighed: weighed,
    weightAt: weightAt,
    weightEntries: weightEntries,
    setWeight: setWeight,
    removeWeight: removeWeight,
    pickDay: pickDay,
    weekTally: weekTally
  };
})();
