/**
 * СКІЛЬКИ ДАНИХ СТОЇТЬ ЗА ЧИСЛОМ — одне правило на весь сайт.
 *
 * ЧОМУ ЦЕ ОКРЕМЕ ЯДРО. Порогів «даних досить» у проєкті було девʼять, у
 * восьми ядрах, і кожен казав «ні» по-своєму: TdeeCore повертав null,
 * HistoryCore — порожній рядок, AdherenceCore — обʼєкт зі state 'nodata',
 * 'openday', 'noplan' або 'resttoday', ProgressCore просто не малював
 * картку. Наслідок видно на екрані: одне число мовчить чесно, друге
 * показує прочерк, а третє видає середнє по трьох днях без жодного
 * застереження — і виглядає рівно так само переконливо, як середнє по
 * тридцяти.
 *
 * Тут не нова математика. Тут одна СЛОВНИКОВА одиниця: «маємо N із
 * потрібних M» і три стани замість двох.
 *
 *   none — немає нічого. Повідомлення людині: «почни».
 *   thin — щось є, але замало. Повідомлення: «ще трохи», і число НЕ
 *          показується. Це найважливіший зі станів: саме його зазвичай
 *          і пропускають, видаючи випадковість за результат.
 *   ok   — досить, число можна показувати.
 *
 * ЧОМУ ТРИ, А НЕ ДВА. «Нічого» і «замало» — різні стани для людини:
 * перший означає, що вона ще не почала, другий — що вже почала і варто
 * продовжити. Злити їх в одне «даних немає» означає сказати тому, хто
 * веде журнал другий тиждень, що його роботи не існує.
 */
(function () {
  'use strict';

  /*
   * Частка вікна, з якої середнє перестає бути випадковим.
   *
   * 0,7 — не з теорії. Це те саме число, яким уже жили виміряні витрати
   * (TdeeCore.MIN_MEAL_SHARE): на 14-денному вікні воно означає 10 днів
   * із записом, і саме на цій межі різниця між «виміряним підтриманням»
   * і формулою перестає стрибати від одного застілля. Правило винесено
   * сюди, щоб наступне вікно не вигадувало собі власну частку.
   */
  var SHARE = 0.7;

  /*
   * Скільки одиниць потрібно ЗАВЖДИ, хоч яке коротке вікно. Одна точка —
   * це не тренд, дві — це відрізок між двома випадковостями. Три — мінімум,
   * на якому видно напрямок; те саме число вже стоїть у ProgressCore
   * (bodyStats) і ExerciseCore.
   */
  var FLOOR = 3;

  function num(v) { var n = Number(v); return Number.isFinite(n) ? n : 0; }

  /**
   * Вердикт: скільки даних є проти того, скільки треба.
   *
   * @param {number} have скільки одиниць реально є
   * @param {number} need розмір вікна (скільки могло б бути)
   * @param {{share?:number, min?:number}} [opts]
   *        share — своя частка замість 0,7 (вікно, де потрібна щільність);
   *        min   — свій мінімум замість трьох (там, де одиниця дорога).
   * @returns {{level:'none'|'thin'|'ok', ok:boolean, have:number,
   *            need:number, want:number, share:number}}
   *          want — скільки одиниць потрібно САМЕ ТУТ: більше з двох
   *          порогів, частки вікна й мінімуму.
   */
  function of(have, need, opts) {
    var h = Math.max(0, Math.round(num(have)));
    var n = Math.max(0, Math.round(num(need)));
    var o = opts || {};
    var sh = num(o.share) > 0 ? num(o.share) : SHARE;
    var floor = num(o.min) > 0 ? Math.round(num(o.min)) : FLOOR;
    /* Вікна може не бути зовсім (need = 0) — тоді лишається мінімум:
       «останні тренування» не мають розміру вікна, але три з них
       потрібні так само. */
    var want = Math.max(floor, Math.ceil(n * sh));
    var level = h === 0 ? 'none' : (h < want ? 'thin' : 'ok');
    return {
      level: level,
      ok: level === 'ok',
      have: h,
      need: n,
      want: want,
      share: n > 0 ? h / n : 0
    };
  }

  /**
   * Відмінок одиниці. Делегат: єдина реалізація — window.App.plural.
   * Без App (наприклад, у пісочниці тестів) береться форма множини —
   * це не друга реалізація правила, а свідома заглушка.
   */
  function form(n, forms) {
    var f = Array.isArray(forms) ? forms : ['день', 'дні', 'днів'];
    var P = window.App && window.App.plural;
    return typeof P === 'function' ? P(n, f[0], f[1], f[2]) : f[2];
  }

  /**
   * Короткий підпис під числом або замість нього.
   *
   * ok   → 'по 12 із 14 днів', і порожньо, коли є все вікно;
   * thin → 'поки 4 із 10 днів';
   * none → 'записів ще немає'.
   *
   * Слово «поки» в thin — навмисне: воно каже, що це тимчасово, а не що
   * функція зламана.
   */
  function label(v, forms) {
    if (!v) return '';
    if (v.level === 'none') return 'записів ще немає';
    if (v.level === 'thin') return 'поки ' + v.have + ' із ' + v.want + ' ' + form(v.want, forms);
    if (v.need && v.have < v.need) {
      return 'по ' + v.have + ' із ' + v.need + ' ' + form(v.need, forms);
    }
    return '';
  }

  /**
   * Значення, якщо даних досить, — інакше null.
   *
   * Саме null, а не нуль і не прочерк: нуль — це виміряне значення, і
   * підставляти його замість «невідомо» означає збрехати тим самим
   * способом, яким середні калорії колись рахували порожні дні.
   */
  function gate(v, value) {
    return v && v.ok ? value : null;
  }

  window.Enough = {
    SHARE: SHARE,
    FLOOR: FLOOR,
    of: of,
    label: label,
    gate: gate
  };
})();
