/**
 * Усі групи, які вправа зачіпає.
 *
 * Використовується для ПОШУКУ й ЗАМІНИ: у випадайці «замінити вправу» на
 * румунську тягу треба натрапити і з боку біцепса стегна, і з боку сідниць.
 * Для підрахунку обʼєму цей список НЕ годиться — див. primaryMuscle нижче.
 */
window.musclesOfExercise = function (ex) {
  if (Array.isArray(ex.muscles) && ex.muscles.length) return ex.muscles;
  return PATTERN_MUSCLES[ex.pattern] || [];
};

/**
 * ГОЛОВНА робоча група — перша в масиві muscles.
 *
 * Саме сюди і тільки сюди йдуть підходи при підрахунку тижневого обʼєму.
 * Раніше код додавав підходи КОЖНІЙ групі вправи, і це прямо суперечило
 * правилу, записаному великими літерами в шапці цього ж файла: 3 підходи
 * румунської тяги ставали 3 підходами біцепса стегна ПЛЮС 3 підходами
 * сідниць, тож смуга «Сідниці» показувала 12/14 замість 6/14, а редактор
 * на цих завищених числах ще й забороняв додати те, що в межу вкладалось.
 *
 * Порядок у masиві muscles тепер значущий: перша група — головна.
 *
 * @returns {string|null}
 */
window.primaryMuscle = function (ex) {
  const ms = window.musclesOfExercise(ex || {});
  return ms.length ? ms[0] : null;
};

/**
 * Багатосуглобова вправа чи ізоляція.
 *
 * Спершу дивимось на поле lift. Якщо його немає — вправу або додав
 * користувач у редакторі плану, або вона прийшла зі старого збереженого
 * плану. Тоді шукаємо однойменну в бібліотеці, і лише потім здаємось.
 *
 * Замовчування — 'isolation'. Помилитись у цей бік не страшно: людина
 * побачить нижчу стелю відсотків, ніж могла б. Помилка в інший бік — це
 * 92% від 1ПМ у махах з гантелями.
 *
 * @param {{name?:string, lift?:string}} ex
 * @returns {'compound'|'isolation'}
 */
window.liftKind = function (ex) {
  if (!ex) return 'isolation';
  if (ex.lift === 'compound' || ex.lift === 'isolation') return ex.lift;
  const known = EXERCISES.find(function (e) { return e.name === ex.name; });
  return (known && known.lift === 'compound') ? 'compound' : 'isolation';
};

/** Вправи з бібліотеки, що працюють хоча б на одну із заданих груп */
window.exercisesForMuscles = function (ids) {
  const want = new Set(ids || []);
  if (!want.size) return [];
  return EXERCISES.filter(function (e) {
    return e.muscles.some(function (m) { return want.has(m); });
  });
};
