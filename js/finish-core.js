/**
 * ДОСТРОКОВЕ ЗАВЕРШЕННЯ ТРЕНУВАННЯ: питати чи ні, і що показати.
 *
 * Ядро без DOM — тут рішення, а не розмітка. Малює вікно js/workout.js.
 *
 * ЧОМУ ПИТАЄМО НЕ ЗАВЖДИ. Раніше кнопка «Завершити тренування» щоразу
 * кидала системний confirm() — і в того, хто закрив усі підходи, теж.
 * Питати людину, яка щойно зробила все заплановане, нема про що: вона
 * вчиться клацати «так» не читаючи, і тоді попередження перестає
 * працювати саме тоді, коли воно справді потрібне. Тепер вікно
 * зʼявляється тільки при НЕДОРОБЛЕНОМУ дні.
 *
 * ЧОМУ ЦИТАТА ПРО БІЛЬ НЕ ЗАВЖДИ ДОРЕЧНА. У застосунку є трекер
 * «Біль / втома», і людина ставить туди чесне число. Показати тому, хто
 * щойно відмітив біль 8 з 10, заклик «терпи» — це підштовхнути її
 * тренуватись через травму. Тому в такі дні добірка звужується до тем,
 * які нікого нікуди не женуть.
 */
(function () {
  'use strict';

  /*
   * Теми: pain — про терпіння й опір; grit — дисципліна й регулярність;
   * strength — сила як наслідок роботи; resume — «не спиняйся зараз»;
   * self — подолання себе.
   *
   * Тексти власні, а не цитати відомих людей: приписувати живій людині
   * слова, яких вона не казала, не можна, а перевіряти автора для
   * кожного рядка з інтернету — робота, якої тут ніхто не зробить.
   */
  var QUOTES = [
    { t: 'grit',     s: 'Форму робить не найкраще тренування, а те, яке ти не пропустив.' },
    { t: 'grit',     s: 'Настрій приходить у процесі. Чекати його перед підходом — марно.' },
    { t: 'grit',     s: 'Дисципліна — це коли рішення ухвалене заздалегідь, і сьогодні його не переголосовують.' },
    { t: 'grit',     s: 'Один пропущений день нічого не важить. Важить те, чим він стане завтра.' },
    { t: 'grit',     s: 'Ти не мусиш хотіти. Ти мусиш почати — хотіння наздожене.' },
    { t: 'strength', s: 'Сила не береться з підходу. Вона береться з тисячі підходів, серед яких є й цей.' },
    { t: 'strength', s: 'Штанга не знає, як ти спав. Вона знає тільки, підняв ти її чи ні.' },
    { t: 'strength', s: 'Слабких місць не буває — буває те, чого ти ще не тренував.' },
    { t: 'resume',   s: 'Половина роботи вже зроблена. Друга половина коштує менше, ніж здається звідси.' },
    { t: 'resume',   s: 'Найдорожчий підхід — той, який ти зробив, коли вже вирішив піти.' },
    { t: 'resume',   s: 'Лишилось небагато. Стільки ж ти витратиш, доки вмовлятимеш себе піти.' },
    { t: 'resume',   s: 'Зупинитись зараз — не відпочинок. Це просто коротший день.' },
    { t: 'self',     s: 'Змагаєшся ти не з людиною поруч, а з тим собою, який учора зупинився раніше.' },
    { t: 'self',     s: 'Тіло здається за десять повторень до того, як справді закінчиться.' },
    { t: 'self',     s: 'Найважче в тренуванні — не вага. Найважче — не домовитись із собою.' },
    { t: 'self',     s: 'Ти вже тут. Найдорожче з усього дня вже позаду.' },
    { t: 'pain',     s: 'Незручно — не те саме, що боляче. Різницю знаєш тільки ти.' },
    { t: 'pain',     s: 'Терпіти варто важкість. Біль — не варто ніколи.' }
  ];

  /*
   * Поріг, за яким тему pain прибираємо. Шкала трекера — 1…10.
   * Сім — це вже «болить помітно», і з цього місця будь-який заклик
   * терпіти читається як порада ігнорувати травму.
   */
  var PAIN_CUT = 7;

  /**
   * Чи питати перед завершенням.
   * @param {{doneSets:number,totalSets:number}} st підсумок дня
   */
  function shouldAsk(st) {
    if (!st) return false;
    var done = Number(st.doneSets) || 0;
    var total = Number(st.totalSets) || 0;
    /* Дня без жодного запланованого підходу не буває, але якщо план
       порожній — питати нема про що. */
    if (total <= 0) return false;
    return done < total;
  }

  /**
   * Чи доречні сьогодні теми про терпіння.
   * @param {object} trackerLog profile.trackerLog
   * @param {string} day ключ дня 'РРРР-ММ-ДД'
   */
  function painToday(trackerLog, day) {
    try {
      var rec = trackerLog && trackerLog.painFatigue && trackerLog.painFatigue[day];
      if (!rec) return 0;
      /* Трекер kind:'pair' пише {pain, fatigue}; старі записи бували
         просто числом. Втома тут ні до чого — женуть себе через БІЛЬ. */
      var v = typeof rec === 'object' ? rec.pain : rec;
      var n = Number(v);
      return isFinite(n) ? n : 0;
    } catch (e) { return 0; }
  }

  /**
   * Випадкова цитата, доречна сьогодні.
   * @param {object}   o
   * @param {object}   [o.trackerLog] profile.trackerLog
   * @param {string}   [o.day]        ключ дня
   * @param {function} [o.rand]       джерело випадковості (для тестів)
   * @returns {{t:string,s:string}}
   */
  function pickQuote(o) {
    o = o || {};
    var rand = typeof o.rand === 'function' ? o.rand : Math.random;
    var hurts = painToday(o.trackerLog, o.day) >= PAIN_CUT;

    var pool = QUOTES.filter(function (q) { return !(hurts && q.t === 'pain'); });
    /* Порожнім пул стати не може — pain лише частина списку, — але
       якщо колись стане, краще віддати щось, ніж undefined. */
    if (!pool.length) pool = QUOTES;

    var i = Math.floor(rand() * pool.length);
    if (!(i >= 0)) i = 0;
    if (i >= pool.length) i = pool.length - 1;
    return pool[i];
  }

  window.FinishCore = {
    QUOTES: QUOTES,
    PAIN_CUT: PAIN_CUT,
    shouldAsk: shouldAsk,
    painToday: painToday,
    pickQuote: pickQuote
  };
})();
