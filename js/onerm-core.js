/**
 * ============================================================================
 *  ЯДРО РАЗОВОГО МАКСИМУМУ (1ПМ)
 * ============================================================================
 *
 * Тут лежить уся математика 1ПМ і нічого крім неї: ні DOM, ні профілю,
 * ні рендеру. Файл використовують дві сторінки — калькулятор (js/onerm.js)
 * і періодизація (js/periodization-core.js).
 *
 * Раніше формули жили всередині onerm.js в замиканні й назовні не
 * віддавались. Періодизації вони потрібні теж, і копіювати їх у другий
 * файл означало б завести дві версії тієї самої математики, які з часом
 * розійдуться. Тому винесено в ядро — так само, як зроблено з харчуванням
 * (js/nutrition-core.js).
 *
 * ----------------------------------------------------------------------------
 * ГОЛОВНЕ, ЩО ТРЕБА РОЗУМІТИ ПРО ЦІ ЧИСЛА
 * ----------------------------------------------------------------------------
 * Жодна формула 1ПМ не «правильна». Усі це регресії, побудовані на вибірках
 * людей, і кожна систематично промахується на своєму краю діапазону.
 * Похибка росте з кількістю повторень: при r > 10 оцінка вже ненадійна,
 * при r > 15 — це радше здогад.
 *
 * Тому ядро віддає не одне число, а розкид кількох формул. Якщо вони
 * розходяться на 10 кг — значить оцінка груба, і ховати це не можна.
 * ============================================================================
 */
(function () {
  'use strict';

  /* ========================================================================
     ФОРМУЛИ
     ======================================================================== */

  /**
   * Сім регресій. Кожна повертає оцінку 1ПМ із ваги w, піднятої на r разів.
   * @type {{id:string,name:string,note:string,fn:(w:number,r:number)=>number}[]}
   */
  const FORMULAS = [
    {
      id: 'epley', name: 'Epley', note: 'Найпоширеніша. Трохи завищує при 5+ повтореннях.',
      fn: function (w, r) { return w * (1 + r / 30); }
    },
    {
      id: 'brzycki', name: 'Brzycki', note: 'Точніша в діапазоні 2–10 повторень. Ламається при r ≥ 37.',
      fn: function (w, r) { return r >= 37 ? NaN : w * 36 / (37 - r); }
    },
    {
      id: 'lombardi', name: 'Lombardi', note: 'Степенева. Консервативна на високих повтореннях.',
      fn: function (w, r) { return w * Math.pow(r, 0.10); }
    },
    {
      id: 'oconner', name: "O'Conner", note: 'Найпростіша лінійна. Найнижчі оцінки з набору.',
      fn: function (w, r) { return w * (1 + 0.025 * r); }
    },
    {
      id: 'lander', name: 'Lander', note: 'Близька до Brzycki, трохи вищі значення.',
      fn: function (w, r) { return r >= 37 ? NaN : 100 * w / (101.3 - 2.67123 * r); }
    },
    {
      id: 'wathen', name: 'Wathen', note: 'Експоненційна. Стабільна на 8–15 повтореннях.',
      fn: function (w, r) { return 100 * w / (48.8 + 53.8 * Math.exp(-0.075 * r)); }
    },
    {
      id: 'mayhew', name: 'Mayhew', note: 'Розроблена на жимі лежачи.',
      fn: function (w, r) { return 100 * w / (52.2 + 41.9 * Math.exp(-0.055 * r)); }
    }
  ];

  /* Межі, за якими числа перестають означати хоч щось.
     Ті самі принципи, що й у LIMITS харчування: перевірка на рівні ядра,
     а не на рівні поля вводу, бо викликати функцію можуть звідки завгодно. */
  const MAX_WEIGHT = 500;   // кг на штанзі; світовий рекорд у присіді ~505
  const MAX_REPS   = 36;    // вище цього Brzycki і Lander діляться на ≤ 0

  function num(v) {
    const n = Number(v);
    return Number.isFinite(n) ? n : null;
  }

  /* ========================================================================
     ПРЯМА ЗАДАЧА: вага × повторення → 1ПМ
     ======================================================================== */

  /**
   * Оцінки всіх семи формул.
   * @param {number} weight підняте обтяження, кг
   * @param {number} reps   скільки разів піднято (до відмови або майже)
   * @returns {{id:string,name:string,note:string,value:number}[]} лише скінченні
   */
  function estimates(weight, reps) {
    const w = num(weight);
    const r = num(reps);
    if (w === null || r === null || w <= 0 || w > MAX_WEIGHT || r < 1 || r > MAX_REPS) return [];

    return FORMULAS.map(function (f) {
      const v = f.fn(w, r);
      return { id: f.id, name: f.name, note: f.note, value: v };
    }).filter(function (x) {
      if (!Number.isFinite(x.value) || x.value <= 0 || x.value >= MAX_WEIGHT * 2) return false;
      /*
       * Відсів ВІДНОСНО введеної ваги, а не лише за абсолютною межею.
       *
       * Абсолютної не вистачало: 100 кг × 30 повторень давали в Brzycki
       * 36·100/(37−30) = 514 кг — це менше за MAX_WEIGHT·2, тож фільтр
       * пропускав, і сторінка показувала 514 кг як оцінку разового максимуму
       * з підписом «розкид 204%».
       *
       * Разовий максимум більший за 2,5 ваги робочого підходу фізіологічно
       * не буває: навіть на 20 повтореннях співвідношення ~2,1. Усе, що вище,
       * означає, що формулу вивели за межі, на яких її калібрували.
       */
      return x.value <= w * 2.5;
    });
  }

  /**
   * Одне число замість семи — медіана оцінок.
   *
   * Саме медіана, а не середнє: Mayhew і Wathen на низьких повтореннях
   * помітно вибиваються вгору, і середнє тягнеться за ними. Медіана до
   * такого викиду байдужа.
   *
   * Один підйом — це вже і є разовий максимум за визначенням, тому r = 1
   * обробляється окремо: формули на одиниці дають 100–109%, бо їх
   * підганяли на багатоповторних підходах.
   *
   * @returns {number|null} кг, або null якщо порахувати нема з чого
   */
  function oneRepMax(weight, reps) {
    const w = num(weight);
    const r = num(reps);
    if (w === null || w <= 0) return null;
    // Нуль або відʼємне — це «підхід не зроблено», а не разовий максимум.
    // Умова r <= 1 ловила і їх теж: oneRepMax(100, 0) повертав 100.
    if (r !== null && r <= 0) return null;
    if (r === 1) return w > MAX_WEIGHT ? null : w;

    /*
     * Медіану беремо з ПОВНОГО набору формул, а санітарну межу
     * застосовуємо вже до результату.
     *
     * Фільтр `value <= w * 2.5` всередині estimates() відсіює окремі
     * формули — і на 23 повтореннях одразу дві (Brzycki і Lander) випадали
     * разом. Набір стрибав із семи на пʼять, медіана з «середнього двох
     * центральних» ставала «одним центральним», і оцінка ПАДАЛА: 100 кг ×
     * 22 давало 169,1 кг, а 100 кг × 23 — 157,5. Більше повторень —
     * менший максимум; для калькулятора це просто неправда.
     *
     * estimates() лишається як є: список формул на сторінці має чесно
     * показувати, яка з них вилетіла за межі застосовності.
     */
    const all = FORMULAS
      .map(function (f) { return f.fn(w, r); })
      .filter(function (v) { return Number.isFinite(v) && v > 0; })
      .sort(function (a, b) { return a - b; });
    if (!all.length) return null;

    const mid = Math.floor(all.length / 2);
    const med = all.length % 2 ? all[mid] : (all[mid - 1] + all[mid]) / 2;
    if (!Number.isFinite(med) || med <= 0) return null;
    // Та сама межа правдоподібності, але тепер до одного числа, а не до
    // кожної формули окремо: понад 2,5 ваги підходу разового максимуму
    // не буває, і показувати таке число як оцінку не можна.
    return med <= w * 2.5 ? med : null;
  }

  /* ========================================================================
     ЗВОРОТНА ЗАДАЧА: % від 1ПМ → скільки повторень
     ======================================================================== */

  /**
   * Відсоток від 1ПМ, який відповідає заданій кількості повторень.
   * Середнє Epley і Brzycki — вони обмежують діапазон із двох боків.
   *
   * @param {number} reps
   * @returns {number} 0…100
   */
  function percentOfMax(reps) {
    const r = num(reps);
    if (r === null || r <= 1) return 100;
    if (r >= MAX_REPS) return 0;
    const epley   = 1 / (1 + r / 30);
    const brzycki = (37 - r) / 36;
    return (epley + brzycki) / 2 * 100;
  }

  /**
   * Обернення percentOfMax: скільки повторень фізично виходить на такому
   * відсотку від 1ПМ. Це і є відповідь на питання «90 кг — це на скільки раз».
   *
   * Аналітично середнє Epley і Brzycki не обертається в один рядок, тому
   * шукаємо двійковим пошуком по монотонній функції. 40 ітерацій дають
   * точність, з якою можна округлювати до цілого повторення й не думати.
   *
   * @param {number} pct 0…100
   * @returns {number|null} повторень, дробом; null якщо поза межами
   */
  function repsAtPercent(pct) {
    const p = num(pct);
    if (p === null || p <= 0 || p > 100) return null;
    if (p >= 100) return 1;

    let lo = 1, hi = MAX_REPS;
    for (let i = 0; i < 40; i++) {
      const mid = (lo + hi) / 2;
      if (percentOfMax(mid) > p) lo = mid; else hi = mid;
    }
    const r = (lo + hi) / 2;
    return Number.isFinite(r) ? r : null;
  }

  /* ========================================================================
     ОКРУГЛЕННЯ ПІД ЗАЛ
     ======================================================================== */

  /**
   * Найменший крок ваги, який реально можна зібрати: пара «млинців» по 1,25 кг.
   * Число 82,3 кг на папері виглядає точним, але зібрати його ніяк.
   */
  const PLATE_STEP = 2.5;

  /**
   * @param {number} kg
   * @param {number} [step] крок, за замовчуванням 2,5 кг
   * @returns {number} кратна кроку вага, не менша за нуль
   */
  function toPlates(kg, step) {
    const w = num(kg);
    const s = num(step);
    const useStep = (s !== null && s > 0) ? s : PLATE_STEP;
    if (w === null || w <= 0) return 0;
    return Math.max(0, Math.round(w / useStep) * useStep);
  }

  /* ======================================================================== */

  window.OneRM = {
    FORMULAS: FORMULAS,
    MAX_WEIGHT: MAX_WEIGHT,
    PLATE_STEP: PLATE_STEP,
    estimates: estimates,
    oneRepMax: oneRepMax,
    percentOfMax: percentOfMax,
    repsAtPercent: repsAtPercent,
    toPlates: toPlates
  };
})();
