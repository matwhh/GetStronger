/**
 * Діапазони повторень — ЄДИНЕ джерело правди.
 *
 * Правило: стаж тренувань + розмір цільової мʼязової групи → діапазон.
 *
 *   Стаж            | Великі групи | Малі групи
 *   ----------------+--------------+-----------
 *   До 1 року       |     8–10     |   10–12
 *   1–2 роки        |     8–10     |   10–12
 *   3–5 років       |     6–8      |   8–10
 *   Понад 5 років   |     6–8      |   8–10
 *
 * Великі групи (груди, спина, квадрицепс, біцепс стегна, сідниці) й малі
 * (усе інше: дельти, руки, ікри, прес, …) НЕ класифікуються тут заново:
 * розмір лежить у MUSCLES (js/exercises.js, поле size), а цільову групу
 * вправи визначає window.primaryMuscle — перша в masсиві muscles. Це ті
 * самі дані, якими вже живуть тижневий обʼєм і час відпочинку.
 *
 * Застосування централізоване: applyPlan() викликають рівно дві точки —
 * loadPlan/basePlan (js/programs.js: «Плани тренувань», «Мій план тренувань») і
 * resolvePlan (js/workout-core.js: «Сьогодні», «Тренування»). Усі чотири
 * типи програм (Full Body, U/L, PPL, UL/PPL) проходять через них, тож
 * окремої логіки на програму немає і бути не може.
 *
 * Чому діапазон НЕ зберігається у профілі: reps — похідне від стажу, а не
 * факт. Зміниш стаж — план перерахується сам при наступному завантаженні,
 * включно зі старими збереженими правками (customPlans): у них reps теж
 * переписується на льоту, бо збережене там значення могло бути пораховане
 * за старим стажем.
 *
 * ВЛАСНЕ ЧИСЛО ЛЮДИНИ (userReps). Діапазон — орієнтир, а не припис, і в
 * «Моєму плані» його можна замінити точним числом. Тоді reps стає цим
 * числом, і воно доїжджає до тренування як є: екран тренування підставляє
 * у підхід не середину діапазону («8–10» → 9, тобто число, якого людина
 * ніде не бачила), а рівно те, що вона поставила.
 *
 * userReps — ФАКТ (людина обрала), тому він, на відміну від reps,
 * зберігається в customPlans і переживає зміну стажу. Порожнє поле знімає
 * його, і вправа повертається до діапазону за таблицею.
 *
 * СТЕЛЯ. Більше MAX.large на велику групу і MAX.small на малу поставити
 * неможливо: значення поза межами мовчки підтягується до стелі і тут, і
 * на читанні — тобто навіть у профілі, привезеному з іншого пристрою або
 * відредагованому руками в експортованому JSON. Ніде в інтерфейсі про цю
 * межу не написано навмисно: це не правило, яке людина мусить памʼятати,
 * а рамка, у якій поле просто не дає вийти за розумне.
 */
(function () {
  'use strict';

  /* Два яруси, а не чотири: перші дві категорії стажу мають однакові
     діапазони, останні дві — теж. Таблиця вище — джерело правди. */
  const RANGES = {
    beginner: { large: '8–10', small: '10–12' },
    advanced: { large: '6–8',  small: '8–10' }
  };

  const TIER_OF = { novice: 'beginner', inter: 'beginner', adv: 'advanced', elite: 'advanced' };

  /*
   * Стеля власного числа. Верхня межа таблиці діапазонів — 12 (малі групи
   * у новачка), тож ці числа її не звужують: вони лише не дають піти в
   * бік, де підхід перестає бути силовим і стає витривалістю. Малим групам
   * дано більше, бо дельти, руки, ікри й прес традиційно й ростуть з
   * вищих повторень — рівно з тієї самої причини, з якої їхній діапазон у
   * таблиці вище за діапазон великих груп.
   */
  const MAX = { large: 12, small: 15 };

  /**
   * Ярус за стажем. Невідомий/відсутній стаж — 'beginner': безпечний
   * запасний варіант для старих профілів, де trainingAge ще не вказано
   * (вищі повторення з меншою вагою — консервативніший вибір).
   */
  function tierFor(trainingAge) {
    return TIER_OF[trainingAge] || 'beginner';
  }

  /** Розмір цільової групи вправи за наявними даними MUSCLES. */
  function sizeOf(ex) {
    const main = typeof window.primaryMuscle === 'function' ? window.primaryMuscle(ex) : null;
    const m = (window.MUSCLES || []).find(function (x) { return x.id === main; });
    return m && m.size === 'large' ? 'large' : 'small';
  }

  /** Діапазон для однієї вправи. */
  function repRangeFor(trainingAge, ex) {
    return RANGES[tierFor(trainingAge)][sizeOf(ex)];
  }

  /** Скільки повторень максимум можна поставити цій вправі руками. */
  function maxRepsFor(ex) {
    return MAX[sizeOf(ex)];
  }

  /**
   * Власне число людини, приведене до меж: ціле 1…maxRepsFor або null.
   *
   * null означає «числа немає» — і для порожнього поля, і для сміття.
   * Завелике число НЕ відкидається, а підтягується до стелі: відкинути
   * означало б мовчки лишити старе значення, і людина побачила б, що поле
   * «не працює». Підтягнуте видно одразу.
   */
  function normUserReps(value, ex) {
    if (value == null || value === '') return null;
    const n = Math.round(Number(String(value).trim()));
    if (!Number.isFinite(n) || n < 1) return null;
    return Math.min(n, maxRepsFor(ex));
  }

  /*
   * СТЕЛЯ RIR — 5, і взята вона не зі стелі.
   *
   * js/periodization-core.js, оцінюючи разовий максимум, однаково
   * обрізає RIR до 5: далі підхід перестає бути силовим і формула
   * Еплі на ньому не працює. Прийняти тут 9 означало б показати число,
   * яке нижче по дорозі мовчки стане пʼятіркою.
   *
   * Нуль — це відповідь, а не порожнеча: «до відмови». Тому порожнє
   * поле дає null («не задано»), а не нуль.
   */
  const RIR_MAX = 5;

  /** Запас до відмови: ціле 0…5, або null для порожнього й сміття. */
  function normRir(value) {
    if (value == null) return null;
    /* Обрізаємо ДО перевірки на порожнечу: Number('   ') — це 0, тобто
       поле з пробілами мовчки означало б «до відмови». */
    const txt = String(value).trim();
    if (txt === '') return null;
    const n = Math.round(Number(txt));
    if (!Number.isFinite(n)) return null;
    return Math.min(Math.max(n, 0), RIR_MAX);
  }

  /**
   * План із перерахованими reps. Повертає НОВІ обʼєкти днів і вправ:
   * resolvePlan віддає посилання прямо в PROGRAMS/customPlans, і запис у
   * них зіпсував би базові дані програм на весь сеанс.
   *
   * Без MUSCLES (сторінка без js/exercises.js) план повертається як є —
   * краще авторські reps, ніж вигадана класифікація.
   */
  function applyPlan(plan, trainingAge) {
    if (!Array.isArray(plan) || !window.MUSCLES) return plan;
    return plan.map(function (day) {
      if (!day || !Array.isArray(day.exercises)) return day;
      return Object.assign({}, day, {
        exercises: day.exercises.map(function (ex) {
          /* Число людини сильніше за таблицю — але тільки в межах стелі,
             і перевіряється воно тут, на ЧИТАННІ. Інакше значення, що
             приїхало з іншого пристрою або з відредагованого руками
             експорту, обійшло б перевірку редактора. */
          const own = normUserReps(ex && ex.userReps, ex);
          const out = Object.assign({}, ex, {
            reps: own === null ? repRangeFor(trainingAge, ex) : String(own)
          });
          if (own === null) delete out.userReps;
          else out.userReps = own;
          return out;
        })
      });
    });
  }

  window.RepsCore = {
    RANGES: RANGES,
    MAX: MAX,
    RIR_MAX: RIR_MAX,
    normRir: normRir,
    tierFor: tierFor,
    sizeOf: sizeOf,
    repRangeFor: repRangeFor,
    maxRepsFor: maxRepsFor,
    normUserReps: normUserReps,
    applyPlan: applyPlan
  };
})();
