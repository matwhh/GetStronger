/**
 * Періоди статистики Get Stronger — одне джерело правди про вікна аналітики.
 *
 * НАВІЩО. Get Stronger накопичує історію з першого дня, але статистика огляду
 * має рахуватись від фіксованої дати старту. Без централізованого місця
 * ця дата розповзлась би по десятку файлів, і додати другий період означало б
 * правити аналітику скрізь. Тут вона одна.
 *
 * ЩО ЦЕ НЕ Є. Це НЕ сезонний рейтинг ELO (db/elo-engine.sql, js/season.js):
 * той живе на сервері, триває три місяці й починається з 0 ELO щокварталу.
 * Тут — інше: період, за який рахується ТРЕНУВАЛЬНА статистика (обʼєм,
 * PR, консистентність). Дві системи навмисно окремі: рейтинг — гейміфікація,
 * статистика — факти.
 *
 * ІСТОРІЯ НЕ ЧІПАЄТЬСЯ. Записи до старту періоду лишаються в журналах і
 * доступні як lifetime-історія (календар, підсумок дня, графіки ваги).
 * Період лише ОБМЕЖУЄ вікно аналітики — нічого не видаляє й не переписує.
 *
 * ДАТИ ЛОКАЛЬНІ. Межа '2026-09-01' означає опівніч за місцевим часом
 * користувача: журнали підписані локальними датами (keyOf), тож порівняння
 * рядків 'YYYY-MM-DD' і є порівнянням у правильному поясі. UTC тут дав би
 * зсув на добу для половини світу.
 *
 * ДОДАТИ ПЕРІОД 2: один запис у SEASONS із start наступного дня. Аналітика
 * не змінюється — вона питає current() і бере його межі.
 */
(function () {
  'use strict';

  /* Порядок від найстарішого до найновішого. end: null — період триває. */
  const SEASONS = [
    { id: 1, name: 'Період 1', start: '2026-09-01', end: null }
  ];

  const DATE_KEY = /^\d{4}-\d{2}-\d{2}$/;

  /** Локальна дата 'YYYY-MM-DD' */
  /* Делегат: єдина реалізація — js/date-core.js. Тут лишається лише
     імʼя, щоб не переписувати 3 місць виклику. Чому одна: копії
     цієї функції встигли розійтись у сімох файлах (див.
     docs/audit/2026-09-12/AUDIT.md). */
  function keyOf(d) { return window.DateCore.keyOf(d); }

  /**
   * Період, активний на дату (за замовчуванням — сьогодні).
   * null, якщо дата раніша за старт першого періоду: до 1 вересня 2026
   * періодів не існує, і аналітика чесно показує lifetime.
   */
  function at(date) {
    const k = DATE_KEY.test(String(date || '')) ? String(date) : keyOf(date);
    for (let i = SEASONS.length - 1; i >= 0; i--) {
      const s = SEASONS[i];
      if (k >= s.start && (s.end === null || k <= s.end)) return s;
    }
    return null;
  }

  /** Поточний період або null. */
  function current(now) { return at(now ? keyOf(now) : keyOf(new Date())); }

  /** Чи належить дата періоду. Межі включні з обох боків. */
  function contains(season, dateKey) {
    if (!season || !DATE_KEY.test(String(dateKey))) return false;
    return dateKey >= season.start && (season.end === null || dateKey <= season.end);
  }

  /**
   * Нижня межа вікна аналітики: перша дата, яку враховувати.
   * Поки період не почався — null (рахуємо всю історію).
   */
  function floorKey(now) {
    const s = current(now);
    return s ? s.start : null;
  }

  /**
   * Обрізати журнал { 'YYYY-MM-DD': ... } до меж періоду.
   * Повертає НОВИЙ обʼєкт — вхідний журнал недоторканий (історія
   * незмінна за побудовою). Без періоду повертає вхідний як є.
   */
  function clip(log, now) {
    const from = floorKey(now);
    if (!from || !log || typeof log !== 'object') return log || {};
    const out = {};
    Object.keys(log).forEach(function (k) {
      if (DATE_KEY.test(k) && k >= from) out[k] = log[k];
    });
    return out;
  }

  /**
   * Те саме для weightLog: { 'Вправа': [{d, kg}] } — інша форма журналу.
   * Вправи, у яких після обрізання не лишилось записів, зникають зі списку.
   */
  function clipSeries(log, now) {
    const from = floorKey(now);
    if (!from || !log || typeof log !== 'object') return log || {};
    const out = {};
    Object.keys(log).forEach(function (name) {
      const arr = Array.isArray(log[name]) ? log[name] : [];
      const kept = arr.filter(function (e) { return e && DATE_KEY.test(e.d) && e.d >= from; });
      if (kept.length) out[name] = kept;
    });
    return out;
  }

  /** Підпис для UI: «Статистика з 1 вересня 2026» або lifetime. */
  function label(now) {
    const s = current(now);
    if (!s) return 'За весь час';
    const MONTHS = ['січня','лютого','березня','квітня','травня','червня',
                    'липня','серпня','вересня','жовтня','листопада','грудня'];
    const p = s.start.split('-').map(Number);
    /*
     * ЧОМУ ТУТ НЕМА СЛОВА «СЕЗОН» (аудит, M7 — вирішено).
     *
     * У Get Stronger два різні періоди, і колись обидва звались сезоном:
     *   • сезонний РЕЙТИНГ (season_of у базі) — календарний квартал,
     *     обнуляється до 0 ELO, має таблицю лідерів і нагороди;
     *   • вікно СТАТИСТИКИ (цей файл) — від фіксованої дати старту, НЕ
     *     обнуляється, нікого ні з ким не порівнює.
     *
     * До 1 грудня 2026 вони збігались за датою, тож різниці ніхто не
     * бачив. Далі рейтинг обнуляється, а це вікно — ні, і людина на
     * сусідніх сторінках бачила б, як «сезон» в одному місці почався
     * заново, а в другому триває. Одне слово на дві різні речі.
     *
     * Рішення: слово «сезон» лишається за рейтингом, а тут стоїть те,
     * чим це насправді є — межа, від якої рахується статистика. Самі
     * періоди не зводяться в один навмисно: рейтинг має обнулятись
     * (інакше новачок нікого не наздожене), а тренувальна статистика —
     * ні (прогрес у залі меряється роками, а не кварталами).
     *
     * Назву періоду (s.name) у підписі не показуємо: людині важлива
     * дата, а не порядковий номер. Вона лишається в реєстрі як
     * ідентифікатор для коду.
     */
    return 'Статистика з ' + p[2] + ' ' + MONTHS[p[1] - 1] + ' ' + p[0];
  }

  window.SeasonCore = {
    SEASONS: SEASONS,
    at: at,
    current: current,
    contains: contains,
    floorKey: floorKey,
    clip: clip,
    clipSeries: clipSeries,
    label: label
  };
})();
