/*
 * ПЕРЕХІД НА ЛІТНІЙ ЧАС З'ЇДАВ ОСТАННЮ КОЛОНКУ.
 *
 * Кількість тижнів рахувалась як різниця двох понеділків у МІСЦЕВИХ
 * мілісекундах, поділена на тиждень, із Math.floor. Доба переходу на
 * літній час триває 23 години, тож вікно, яке цей перехід перетинає,
 * давало n − 0,006 тижня — і floor знімав цілу колонку. Разом із нею
 * зникав СЬОГОДНІШНІЙ день: по його клітинці не можна було тапнути.
 *
 * Помилка жила по пів року поспіль (від кінця березня, поки вікно
 * містить перехід) і на око виглядала як «календар просто закінчується
 * минулого тижня».
 *
 * Те саме число поруч рахує js/journal.js через Math.round — тобто це
 * був недогляд, а не рішення. Тепер обидва йдуть через
 * DateCore.daysBetween, який рахує в UTC саме з цієї причини.
 */
describe('DayCal: вікно через перехід на літній час', () => {
  /** Ключі днів, які сітка справді намалювала */
  const drawn = (from, to) => {
    const seen = [];
    DayCal.html({ from: from, to: to, marks: {}, cell: (k) => { seen.push(k); return null; } });
    return seen.sort();
  };

  it('сьогодні намальоване, коли вікно перетинає перехід', () => {
    /* 29 березня 2026 — перехід на літній час у Європі. Вікно на сім
       місяців назад від вересня його містить. */
    const days = drawn('2026-02-17', '2026-09-17');
    assert.equal(days[days.length - 1], '2026-09-17',
      'останній намальований день: ' + days[days.length - 1]);
  });

  it('і в жовтні, поки вікно ще дотягує до березня', () => {
    const days = drawn('2026-03-24', '2026-10-24');
    assert.equal(days[days.length - 1], '2026-10-24',
      'останній намальований день: ' + days[days.length - 1]);
  });

  it('вікно без переходу як працювало, так і працює', () => {
    const days = drawn('2026-05-01', '2026-09-17');
    assert.equal(days[days.length - 1], '2026-09-17');
  });
});
