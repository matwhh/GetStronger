/**
 * ДВА ЖУРНАЛИ ДНЯ: тренування і вага.
 *
 * Ядро зʼявилось у вересні 2026, коли плитки «Сьогодні» отримали власні
 * сторінки вводу. До того питання «чи був цього дня тренувальний день»
 * відповідали ДВА файли по-своєму — journal.js і today.js, — і код у них
 * збігався «майже». Саме «майже» тут і небезпечне: журнал умів явний
 * нуль як «знято руками», і якби наступна правка зачепила лише один із
 * двох, теплокарта в «Прогресі» й квадратик на головній почали б
 * розповідати про той самий день різне. Мовчки.
 *
 * Тому найважливіші тести тут — не про щасливий шлях, а про три речі,
 * які ламаються тихо:
 *   1. явний 0 у workLog ПЕРЕКРИВАЄ сесію (інакше день, зарахований
 *      підходами, неможливо зняти взагалі);
 *   2. функції запису повертають НОВИЙ обʼєкт (мутація вхідного журналу
 *      показала б новий стан ще до того, як збереження підтвердилось);
 *   3. кома в полі ваги — робочий ввід, а не помилка: на українській
 *      розкладці телефона на цифровій клавіатурі стоїть саме вона.
 */
import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { loadModules } from './helpers.js';

const w = loadModules(['js/date-core.js', 'js/daylog-core.js']);
const DL = w.DayLogCore;

/* ------------------------------------------------------------------ */
describe('чи був день тренувальним', () => {
  const SESS = { '2026-09-01': { done: 0, doneSets: 4, totalSets: 8 } };

  test('порожні журнали — жодного тренування', () => {
    assert.equal(DL.trained({}, {}, '2026-09-01'), false);
    assert.equal(DL.trained(null, null, '2026-09-01'), false);
  });

  test('ручна позначка 1 — тренування', () => {
    assert.equal(DL.trained({ '2026-09-01': 1 }, {}, '2026-09-01'), true);
  });

  test('сесія з закритими підходами — тренування без позначки', () => {
    assert.equal(DL.trained({}, SESS, '2026-09-01'), true);
  });

  /* Регресія: done — це закриті ВПРАВИ. Відколи виконання відмічається
     по підходах, день із чотирма закритими підходами і жодною добитою
     вправою мав done === 0, і календар лишався порожнім. */
  test('самих doneSets достатньо, done може бути нулем', () => {
    assert.equal(DL.sessionCounts({ done: 0, doneSets: 3 }), true);
    assert.equal(DL.sessionCounts({ done: 0, doneSets: 0 }), false);
    assert.equal(DL.sessionCounts(null), false);
  });

  /* Регресія: до появи явного нуля перемикач умів лише delete, і день,
     підсвічений сесією, зняти було неможливо — він далі годував
     статистику плану й рейтинг, а підказка «клікніть, щоб зняти» була
     неправдою. */
  test('явний 0 перекриває сесію', () => {
    assert.equal(DL.hasSession(SESS, '2026-09-01'), true, 'сесія під днем є');
    assert.equal(DL.trained({ '2026-09-01': 0 }, SESS, '2026-09-01'), false,
      'явний 0 має перемогти сесію');
  });
});

/* ------------------------------------------------------------------ */
describe('перемикач дня', () => {
  const SESS = { '2026-09-01': { doneSets: 4, totalSets: 8 } };

  test('порожній день → 1', () => {
    assert.equal(DL.toggleTrained({}, {}, '2026-09-01')['2026-09-01'], 1);
  });

  test('ручна позначка знімається видаленням ключа, а не нулем', () => {
    const out = DL.toggleTrained({ '2026-09-01': 1 }, {}, '2026-09-01');
    assert.equal('2026-09-01' in out, false);
  });

  test('день із сесією знімається явним нулем', () => {
    const out = DL.toggleTrained({}, SESS, '2026-09-01');
    assert.equal(out['2026-09-01'], 0);
    assert.equal(DL.trained(out, SESS, '2026-09-01'), false);
  });

  test('знятий день із сесією вмикається назад', () => {
    const out = DL.toggleTrained({ '2026-09-01': 0 }, SESS, '2026-09-01');
    assert.equal(out['2026-09-01'], 1);
  });

  test('вхідний журнал не мутується', () => {
    const src = { '2026-09-01': 1 };
    DL.toggleTrained(src, {}, '2026-09-01');
    assert.equal(src['2026-09-01'], 1);
  });

  test('зіпсований ключ нічого не пише', () => {
    const out = DL.toggleTrained({}, {}, 'позавчора');
    assert.equal(Object.keys(out).length, 0);
  });

  test('markTrained ставить 1 незалежно від стану', () => {
    assert.equal(DL.markTrained({ '2026-09-01': 0 }, '2026-09-01')['2026-09-01'], 1);
  });
});

/* ------------------------------------------------------------------ */
describe('рівень дня 0–4', () => {
  test('немає тренування — 0', () => {
    assert.equal(DL.dayLevel({}, {}, '2026-09-01'), 0);
  });

  /* Рівень 1 стоїть окремо навмисно: поставити його поруч із «менше
     половини» означало б сказати про день те, чого в даних немає. */
  test('позначено руками — 1, а не 2', () => {
    assert.equal(DL.dayLevel({ '2026-09-01': 1 }, {}, '2026-09-01'), 1);
  });

  test('частки підходів дають 2, 3 і 4', () => {
    const lvl = (done, total) =>
      DL.dayLevel({}, { k: { doneSets: done, totalSets: total } }, 'k');
    assert.equal(lvl(2, 8), 2);
    assert.equal(lvl(6, 8), 3);
    assert.equal(lvl(8, 8), 4);
  });

  test('підписів рівно пʼять — по одному на рівень', () => {
    assert.equal(DL.LEVEL_TEXT.length, 5);
  });
});

/* ------------------------------------------------------------------ */
describe('розбір ваги з поля', () => {
  test('кома — робочий ввід', () => {
    assert.equal(DL.parseKg('82,4'), 82.4);
  });

  test('пробіли обрізаються', () => {
    assert.equal(DL.parseKg('  81.9 '), 81.9);
  });

  /* Пів кроку побутових ваг. Точніші цифри — ілюзія точності: різниця в
     30 грамів між двома ранками це вода, а не тіло. */
  test('крок 0,1 кг', () => {
    assert.equal(DL.parseKg('82.44'), 82.4);
    assert.equal(DL.parseKg('82.46'), 82.5);
  });

  test('порожнє, текст і межі — null', () => {
    assert.equal(DL.parseKg(''), null);
    assert.equal(DL.parseKg('   '), null);
    assert.equal(DL.parseKg('вісімдесят'), null);
    assert.equal(DL.parseKg(null), null);
    assert.equal(DL.parseKg('29.9'), null);
    assert.equal(DL.parseKg('300.1'), null);
  });

  test('самі межі приймаються', () => {
    assert.equal(DL.parseKg(String(DL.W_MIN)), DL.W_MIN);
    assert.equal(DL.parseKg(String(DL.W_MAX)), DL.W_MAX);
  });
});

