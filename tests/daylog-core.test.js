describe('вибір дня для запису', () => {
  test('порожній і зіпсований відкочуються на сьогодні', () => {
    assert.equal(DL.pickDay('', '2026-09-12'), '2026-09-12');
    assert.equal(DL.pickDay('позавчора', '2026-09-12'), '2026-09-12');
    assert.equal(DL.pickDay(null, '2026-09-12'), '2026-09-12');
  });

  /* Ключ у стані переживає північ: вчорашній вибір «завтра» зранку став
     би записом ваги за день, який ще не настав. */
  test('майбутній день відкочується на сьогодні', () => {
    assert.equal(DL.pickDay('2026-09-13', '2026-09-12'), '2026-09-12');
  });

  test('минулий день лишається', () => {
    assert.equal(DL.pickDay('2026-09-05', '2026-09-12'), '2026-09-05');
  });
});

