describe('скільки днів тижня має факт', () => {
  /* Понеділок 7 вересня 2026. Рахуємо рівно 7 днів від нього, а не
     «останні 7»: підпис «цього тижня» на «Сьогодні» й на окремій
     сторінці мусить давати те саме число. */
  const MON = '2026-09-07';

  test('рахує рівно вікно понеділок–неділя', () => {
    const log = { '2026-09-06': 82, '2026-09-07': 82, '2026-09-09': 82, '2026-09-14': 82 };
    assert.equal(DL.weekTally(k => DL.weighed(log, k), MON), 2);
  });

  test('порожній тиждень — нуль', () => {
    assert.equal(DL.weekTally(() => false, MON), 0);
  });

  test('повний тиждень — сім', () => {
    assert.equal(DL.weekTally(() => true, MON), 7);
  });
});
