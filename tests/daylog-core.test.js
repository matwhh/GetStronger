describe('журнал ваги', () => {
  const LOG = { '2026-09-03': 82.1, '2026-09-01': 82.6, 'сміття': 80, '2026-09-02': 'ой' };

  test('записи відсортовані й очищені від сміття', () => {
    assert.equal(DL.weightEntries(LOG).map(e => e.key).join(','),
                 '2026-09-01,2026-09-03');
  });

  test('вага поза фізіологічними межами не читається', () => {
    assert.equal(DL.weightAt({ k: 5 }, 'k'), null);
    assert.equal(DL.weighed({ k: 0 }, 'k'), false);
    assert.equal(DL.weighed({ '2026-09-01': 82.1 }, '2026-09-01'), true);
  });

  test('запис повертає новий обʼєкт і не чіпає вхідний', () => {
    const src = { '2026-09-01': 82.6 };
    const out = DL.setWeight(src, '2026-09-02', '83,1');
    assert.equal(out['2026-09-02'], 83.1);
    assert.equal('2026-09-02' in src, false);
  });

  test('невалідне число не пишеться зовсім', () => {
    const out = DL.setWeight({}, '2026-09-02', 'ой');
    assert.equal(Object.keys(out).length, 0);
  });

  test('видалення теж адресне', () => {
    const src = { a: 1, '2026-09-01': 82.6 };
    const out = DL.removeWeight(src, '2026-09-01');
    assert.equal('2026-09-01' in out, false);
    assert.equal(src['2026-09-01'], 82.6);
  });
});

